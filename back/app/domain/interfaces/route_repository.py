from __future__ import annotations

from datetime import date, datetime
from typing import Protocol


class RouteAlreadyExists(Exception):
    """El índice único (date, province_id) rechazó la orden: esa provincia ya tiene orden ese día."""


class RouteRepository(Protocol):
    # Orden con sus paradas en secuencia: {id, date, province_id, transporter_id, status, arrived_at, stops}.
    def get(self, route_id: int) -> dict | None: ...
    def route_for(self, day: date, province_id: int) -> dict | None: ...
    # Las paradas toman la secuencia 1..n en el orden recibido; devuelve el id de la orden.
    def add_route(self, day: date, province_id: int, transporter_id: int | None, center_ids: list[int]) -> int: ...
    # Centros activos con muestras listas para retirar, agrupados por provincia: {province_id: [center_id]}.
    def centers_with_ready_samples(self) -> dict[int, list[int]]: ...
    # Órdenes del día con su provincia y avance: {id, date, province_id, province, status, arrived_at, stops, picked_up}.
    def routes_for_day(self, day: date) -> list[dict]: ...
    # Orden con provincia y paradas en secuencia, cada una con su centro y sus muestras (sample_ids, sample_codes):
    # antes del retiro, las listas del centro; después, las retiradas.
    def route_detail(self, route_id: int) -> dict | None: ...
    # Condicionales: False si otro pedido ya retiró la parada o registró la llegada.
    def mark_stop_picked(self, stop_id: int, at: datetime) -> bool: ...
    def add_pickups(self, stop_id: int, sample_ids: list[int]) -> None: ...
    def mark_arrived(self, route_id: int, at: datetime) -> bool: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
